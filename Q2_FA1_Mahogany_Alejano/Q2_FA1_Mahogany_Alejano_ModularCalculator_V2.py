#Version 2: Improved Modular Calculator
#This program uses functions to perform arithmetic operations.

#Function for addition
def add_numbers(num1, num2):
    return num1 + num2


#Function for subtraction
def subtract_numbers(num1, num2):
    return num1 - num2


#Function for multiplication
def multiply_numbers(num1, num2):
    return num1 * num2


#Function for division
def divide_numbers(num1, num2):
    if num2 == 0:
        return None
    return num1 / num2


#Get the user's input
num1 = float(input("Enter first number: "))
num2 = float(input("Enter second number: "))

#Display the operation menu
print("\n===== MODULAR CALCULATOR =====")
print("1 - Addition")
print("2 - Subtraction")
print("3 - Multiplication")
print("4 - Division")

choice = input("Enter your choice (1-4): ")

#Call the selected function and store its return value
if choice == "1":
    result = add_numbers(num1, num2)
elif choice == "2":
    result = subtract_numbers(num1, num2)
elif choice == "3":
    result = multiply_numbers(num1, num2)
elif choice == "4":
    result = divide_numbers(num1, num2)
else:
    result = "Invalid choice"

#Display the result or an error message
print("\n===== CALCULATION RESULT =====")

if choice not in ("1", "2", "3", "4"):
    print("Error: Please choose a number from 1 to 4.")
elif choice == "4" and num2 == 0:
    print("Error: Cannot divide by zero.")
else:
    print(f"Result: {result:g}")

print("==============================")

